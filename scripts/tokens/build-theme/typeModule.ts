import type { SemanticThemeTypography } from '#tokens/types';
import { cssVarName, toKebabCase } from './utils';
import { varPrefixes } from './types';

const camelCase = (key: string) => key.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

// One class per text style, so a component applies `typography.headingLg` and sets only color and
// spacing. Headings and titles also reset their margin (D-130). The layer keeps these below every
// unlayered component rule, so a component's own media-query size always wins whatever the bundle order.
export function renderTypeModule(styles: SemanticThemeTypography['styles']) {
  const cssProps = {
    family: 'font-family',
    size: 'font-size',
    weight: 'font-weight',
    'line-height': 'line-height',
  } as const;
  const classes = Object.keys(styles).map((name) => {
    const props = Object.entries(cssProps).map(
      ([token, css]) => `    ${css}: var(${cssVarName(varPrefixes.fontStyle, name, token)});`,
    );
    const margin = /^(title|heading)-/.test(name) ? ['    margin: 0;'] : [];
    return `  .${camelCase(toKebabCase(name))} {\n${[...margin, ...props].join('\n')}\n  }`;
  });

  return `/* Generated by scripts/tokens/build-theme.ts from the text styles in defaultTheme.ts. Do not edit.
   Apply a class in the component (\`className={clsx(typography.headingLg, styles.title)}\`) and set only
   color and spacing there. The layer keeps these below every unlayered component rule, so a component's
   own media-query size always wins whatever the bundle order. */

@layer type {
${classes.join('\n\n')}
}
`;
}
