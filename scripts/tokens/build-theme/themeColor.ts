// The browser's theme-color (the tab and address bar tint on phones) is the page surface in each
// mode. It has to be a hex value in a meta tag, so it is converted here from the surface token
// and written to src/tokens/themeColor.ts, which index.html and ThemeProvider read.

const OKLCH = /^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)(?:deg)?\s*\)$/;

export function oklchToHex(value: string): string {
  const match = OKLCH.exec(value.trim());
  if (!match) throw new Error(`themeColor: cannot read ${value}, expected oklch(L% C Hdeg)`);
  const l = Number(match[1]) / 100;
  const c = Number(match[2]);
  const h = (Number(match[3]) * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);

  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  const channel = (x: number) => {
    const clamped = Math.min(1, Math.max(0, x));
    const encoded = clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * clamped ** (1 / 2.4) - 0.055;
    return Math.round(encoded * 255)
      .toString(16)
      .padStart(2, '0');
  };
  return `#${linear.map(channel).join('')}`;
}

export function renderThemeColorModule(light: string, dark: string): string {
  return `// Generated by scripts/tokens/build-theme.ts from surface.default. Do not edit.
export const themeColor = {
  light: '${oklchToHex(light)}',
  dark: '${oklchToHex(dark)}',
} as const;
`;
}
